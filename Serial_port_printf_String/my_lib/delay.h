#ifndef _DELAY_H_
#define _DELAY_H_

#include "stm32f10x.h"

/* 初始化延迟模块
 * 说明：
 * 1. 内部使用 SysTick 生成 1 ms 基准时钟
 * 2. 本函数支持重复调用，实际初始化只会执行一次
 */
void Delay_Init(void);

/* 毫秒级阻塞延时
 * 参数 ms : 延时时长，单位 ms
 * 注意：
 * 1. 本函数为忙等待，延时期间 CPU 不执行其他任务
 * 2. 不建议在中断服务函数中调用
 */
void Delay(uint32_t ms);

/* 获取当前系统节拍计数
 * 返回值：当前毫秒计数，单位 ms
 */
uint32_t GetTick(void);

/* 获取当前运行时间
 * 返回值：当前时间，单位 us
 * 说明：返回值基于 SysTick 当前计数值和毫秒节拍综合换算
 */
uint64_t GetUs(void);

/* 微秒级阻塞延时
 * 参数 us : 延时时长，单位 us
 * 注意：
 * 1. 本函数同样为忙等待
 * 2. 延时精度受 SysTick 时钟源和中断响应时序影响
 */
void DelayUs(uint32_t us);

#endif
